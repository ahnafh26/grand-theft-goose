// tools/build-waterloo-layers.mjs — writes the two layers tools/build-geodata.mjs packs beside GEO, for Waterloo:
//   js/waterloo-poles.js        window.CITY.POLES: street-light poles from OpenStreetMap (highway=street_lamp), in the
//                               shape tools/build-poles.mjs gives Toronto's surveyed poles (type 6006 = street light)
//   js/waterloo-parked-cars.js  window.CITY.PARKED_CARS: no curb-parked cars yet (Waterloo has no by-law dataset here)
// usage: GEO_DATA=tools/data-waterloo node tools/build-waterloo-layers.mjs
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { toWorld, load, log } from './geo-base.mjs';

const out = (f) => fileURLToPath(new URL(`../js/${f}`, import.meta.url));

// ---------- street-light poles ----------
const lamps = load('osm_props.json').elements.filter((e) => e.tags?.highway === 'street_lamp' && e.lat !== undefined);
lamps.sort((a, b) => a.id - b.id);
const ids = [];
const xz = [];
let prev = 0;
for (const e of lamps) {
  const [x, z] = toWorld(e.lon, e.lat);
  ids.push(e.id - prev);
  prev = e.id;
  xz.push(Math.round(x * 10), Math.round(z * 10));
}
const POLES = {
  source: { package: 'openstreetmap', url: 'https://www.openstreetmap.org/copyright', resource: 'highway=street_lamp (Overpass)', licence: 'ODbL' },
  counts: { 6006: lamps.length },
  misc: {},
  tram: [],
  shipped: [6006],
  types: { 6006: { name: 'Street Light Pole', ids, xz } },
  looks: { wood: [], lantern: [], promenade: [], park: [], trolley: [], trolleyCentre: [] },
};
fs.writeFileSync(
  out('waterloo-poles.js'),
  `// js/waterloo-poles.js — GENERATED by tools/build-waterloo-layers.mjs from OpenStreetMap (ODbL), do not edit by hand.\n(function () { window.CITY = window.CITY || {}; window.CITY.POLES = ${JSON.stringify(POLES)}; })();\n`,
);

// ---------- parked cars (none yet) ----------
const PARKED_CARS = {
  generator: 'tools/build-waterloo-layers.mjs (no Waterloo curb-parking data yet)',
  counts: { stalls: 0, cars: 0 },
  cat: [], heading: [], side: [], major: [], minor: [], cx: [], cz: [], cy: [],
};
fs.writeFileSync(
  out('waterloo-parked-cars.js'),
  `// js/waterloo-parked-cars.js — GENERATED by tools/build-waterloo-layers.mjs, do not edit by hand.\n(function () { window.CITY = window.CITY || {}; window.CITY.PARKED_CARS = ${JSON.stringify(PARKED_CARS)}; })();\n`,
);
log(`waterloo layers: ${lamps.length} street-light poles, 0 parked cars`);
